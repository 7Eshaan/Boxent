//! The seccomp profile applied to every process in a sandbox.
//!
//! An allowlist modelled on Docker's default profile, with these left out on purpose:
//! - kernel attack surface with a poor security record: `io_uring_*`, `bpf`, `userfaultfd`,
//!   `perf_event_open`, `keyctl` and the other key-management calls;
//! - anything that changes namespaces or mounts: `unshare`, `setns`, `mount` and the new mount
//!   API, `pivot_root`, `chroot`, `clone`/`clone3` with namespace flags;
//! - process inspection across boundaries: `ptrace`, `process_vm_*`, `kcmp`, `pidfd_getfd`;
//! - host-level controls: modules, `kexec`, `reboot`, clocks, swap, quotas, `syslog`, `acct`;
//! - file-handle tricks: `open_by_handle_at`, `name_to_handle_at`.
//!
//! `socket` is allowed except for `AF_VSOCK`: the sandbox runs inside a VM on macOS, and a vsock
//! socket would reach the hypervisor host directly, bypassing the network namespace.
//!
//! Denied calls fail with EPERM, so programs see an ordinary error rather than being killed.
//! `clone3` fails with ENOSYS so that libc falls back to `clone`, whose flags can be filtered.

use serde_json::{Value, json};

