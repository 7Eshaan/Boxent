/// libseccomp architecture names for the host this driver was built for.
fn architectures() -> Vec<&'static str> {
    if cfg!(target_arch = "aarch64") {
        vec!["SCMP_ARCH_AARCH64"]
    } else if cfg!(target_arch = "x86_64") {
        vec!["SCMP_ARCH_X86_64"]
    } else {
        vec![]
    }
}

/// The `linux.seccomp` section of the OCI config.
pub fn profile() -> Value {
    json!({
        "defaultAction": "SCMP_ACT_ERRNO",
        "defaultErrnoRet": EPERM,
        "architectures": architectures(),
        "syscalls": [
            { "names": ALLOWED, "action": "SCMP_ACT_ALLOW" },
            {
                "names": ["clone"],
                "action": "SCMP_ACT_ALLOW",
                "args": [{ "index": 0, "value": CLONE_NAMESPACE_FLAGS, "valueTwo": 0, "op": "SCMP_CMP_MASKED_EQ" }]
            },
            { "names": ["clone3"], "action": "SCMP_ACT_ERRNO", "errnoRet": ENOSYS },
            {
                "names": ["socket"],
                "action": "SCMP_ACT_ALLOW",
                "args": [{ "index": 0, "value": AF_VSOCK, "op": "SCMP_CMP_NE" }]
            }
        ]
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn denied_calls_are_not_allowed() {
        for d in DENIED {
            assert!(!ALLOWED.contains(d), "{d} is both allowed and denied");
        }
        for special in ["clone", "clone3", "socket"] {
            assert!(
                !ALLOWED.contains(&special),
                "{special} must only be allowed with filters"
            );
        }
    }

    #[test]
    fn no_duplicates() {
        let mut v = ALLOWED.to_vec();
        v.sort_unstable();
        v.dedup();
        assert_eq!(v.len(), ALLOWED.len());
    }

    #[test]
    fn profile_shape() {
        let p = profile();
        assert_eq!(p["defaultAction"], "SCMP_ACT_ERRNO");
        assert_eq!(p["syscalls"].as_array().unwrap().len(), 4);
        assert!(!p["architectures"].as_array().unwrap().is_empty());
    }
}
